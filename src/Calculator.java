public class Calculator {

    /**
     * Impressive method for adding two numbers
     * @param sumant1
     * @param sumant2
     * @return
     */
    public static int sum(int sumant1, int sumant2) {
        return sumant1 + sumant2;
    }

    /**
     * Multiply two numbers
     * @param factor1
     * @param factor2
     * @return
     */
    public static int multiply(int factor1, int factor2) {
        return factor1 * factor2;
    }

}
